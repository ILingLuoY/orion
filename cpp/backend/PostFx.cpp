bool ensureFGUIResources(
    uint32_t width,
    uint32_t height
)
{
    if(
        g_device ==
            VK_NULL_HANDLE ||

        g_physicalDevice ==
            VK_NULL_HANDLE ||

        width == 0 ||

        height == 0 ||

        g_fgBackbufferFormat ==
            VK_FORMAT_UNDEFINED ||

        g_fgUIAlphaPipeline ==
            VK_NULL_HANDLE ||

        g_fgUIAlphaDescriptorSet ==
            VK_NULL_HANDLE ||

        g_fgUISnapshotSampler ==
            VK_NULL_HANDLE
    )
    {
        return false;
    }


    if(
        g_fgHudlessImage !=
            VK_NULL_HANDLE &&

        g_fgFinalImage !=
            VK_NULL_HANDLE &&

        g_fgUIAlphaImage !=
            VK_NULL_HANDLE &&

        g_fgSnapshotFormat ==
            g_fgBackbufferFormat &&

        g_fgUIWidth ==
            width &&

        g_fgUIHeight ==
            height
    )
    {
        return true;
    }


    VkFormatProperties snapshotProperties{};

    vkGetPhysicalDeviceFormatProperties(
        g_physicalDevice,
        g_fgBackbufferFormat,
        &snapshotProperties
    );


    const VkFormatFeatureFlags
        snapshotRequired =
            VK_FORMAT_FEATURE_BLIT_DST_BIT |
            VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT;


    if(
        (
            snapshotProperties.optimalTilingFeatures &
            snapshotRequired
        ) !=
        snapshotRequired
    )
    {
        fprintf(
            stderr,
            "[FG-4.1 RESOURCES]"
            " unsupported snapshot format=%d"
            " features=0x%X\n",

            static_cast<int>(
                g_fgBackbufferFormat
            ),

            static_cast<unsigned int>(
                snapshotProperties.optimalTilingFeatures
            )
        );

        fflush(stderr);

        return false;
    }


    VkFormatProperties alphaProperties{};

    vkGetPhysicalDeviceFormatProperties(
        g_physicalDevice,
        VK_FORMAT_R32_SFLOAT,
        &alphaProperties
    );


    const VkFormatFeatureFlags
        alphaRequired =
            VK_FORMAT_FEATURE_STORAGE_IMAGE_BIT |
            VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT;


    if(
        (
            alphaProperties.optimalTilingFeatures &
            alphaRequired
        ) !=
        alphaRequired
    )
    {
        fprintf(
            stderr,
            "[FG-4.1 RESOURCES]"
            " R32_SFLOAT unsupported"
            " features=0x%X\n",

            static_cast<unsigned int>(
                alphaProperties.optimalTilingFeatures
            )
        );

        fflush(stderr);

        return false;
    }

    if(
        g_fgHudlessImage !=
            VK_NULL_HANDLE ||

        g_fgFinalImage !=
            VK_NULL_HANDLE ||

        g_fgUIAlphaImage !=
            VK_NULL_HANDLE
    )
    {
        const VkResult idleResult =
            FGDeviceWaitIdle(
                g_device
            );


        if(
            idleResult !=
            VK_SUCCESS
        )
        {
            fprintf(
                stderr,
                "[FG-4.1 RESOURCES]"
                " waitIdle failed result=%d\n",

                static_cast<int>(
                    idleResult
                )
            );

            fflush(stderr);

            return false;
        }
    }


    destroyFGUIImages();


    try
    {
        createFGImage(
            width,
            height,
            g_fgBackbufferFormat,

            VK_IMAGE_USAGE_TRANSFER_DST_BIT |
            VK_IMAGE_USAGE_SAMPLED_BIT,

            g_fgHudlessImage,
            g_fgHudlessMemory,
            g_fgHudlessView
        );


        createFGImage(
            width,
            height,
            g_fgBackbufferFormat,

            VK_IMAGE_USAGE_TRANSFER_DST_BIT |
            VK_IMAGE_USAGE_SAMPLED_BIT,

            g_fgFinalImage,
            g_fgFinalMemory,
            g_fgFinalView
        );


        createFGImage(
            width,
            height,
            VK_FORMAT_R32_SFLOAT,

            VK_IMAGE_USAGE_STORAGE_BIT |
            VK_IMAGE_USAGE_SAMPLED_BIT,

            g_fgUIAlphaImage,
            g_fgUIAlphaMemory,
            g_fgUIAlphaView
        );
    }
    catch(const std::exception& e)
    {
        fprintf(
            stderr,
            "[FG-4.1 RESOURCES]"
            " create failed: %s\n",
            e.what()
        );

        fflush(stderr);

        destroyFGUIImages();

        return false;
    }


    g_fgSnapshotFormat =
        g_fgBackbufferFormat;

    g_fgUIWidth =
        width;

    g_fgUIHeight =
        height;


    g_fgHudlessLayout =
        VK_IMAGE_LAYOUT_UNDEFINED;

    g_fgFinalLayout =
        VK_IMAGE_LAYOUT_UNDEFINED;

    g_fgUIAlphaLayout =
        VK_IMAGE_LAYOUT_UNDEFINED;


    updateFGUIAlphaDescriptor();


    fprintf(
        stderr,
        "[FG-4.1 RESOURCES]"
        " size=%ux%u"
        " snapshotFormat=%d"
        " uiAlphaFormat=R32_SFLOAT\n",

        width,
        height,

        static_cast<int>(
            g_fgSnapshotFormat
        )
    );

    fflush(stderr);


    return true;
}


