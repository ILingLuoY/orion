void ensureSdrAces2LutBuffer()
{
    if(g_sdrAces2LutBuffer != VK_NULL_HANDLE)
    {
        return;
    }
    createBuffer(
        g_device,
        g_physicalDevice,
        sizeof(Aces2LutGpuData),
        VK_BUFFER_USAGE_STORAGE_BUFFER_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
        g_sdrAces2LutBuffer,
        g_sdrAces2LutMemory,
        true
    );
    void* mapped = nullptr;
    check(
        vkMapMemory(g_device, g_sdrAces2LutMemory, 0, sizeof(Aces2LutGpuData), 0, &mapped),
        "map ACES2 LUT buffer failed"
    );
    std::memcpy(mapped, &kAces2LutData, sizeof(Aces2LutGpuData));
    vkUnmapMemory(g_device, g_sdrAces2LutMemory);
}
